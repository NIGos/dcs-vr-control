// Target of a RIP-relative operand: disp32 at insn + dispOffset, instruction
// length insnLen (e.g. 48 8B 05 disp32: dispOffset 3, insnLen 7).
inline uint8_t* RipTarget(const uint8_t* insn, int dispOffset, int insnLen) {
  int32_t d;
  memcpy(&d, insn + dispOffset, 4);
  return const_cast<uint8_t*>(insn) + insnLen + d;
}

// Target of an E8/E9 rel32 call or jump; nullptr for anything else.
inline uint8_t* Rel32Target(const uint8_t* insn) {
  if (insn[0] != 0xE8 && insn[0] != 0xE9) return nullptr;
  return RipTarget(insn, 1, 5);
}

// ---------------------------------------------------------------------------
// RTTI (MSVC x64: vtable[-1] -> complete object locator, all fields RVAs)
// ---------------------------------------------------------------------------

struct Col {  // RTTICompleteObjectLocator, signature 1 (image-relative)
  uint32_t signature, offset, cdOffset, typeDescriptor, classDescriptor, self;
};

inline bool InImage(const uint8_t* base, const void* p, size_t n) {
  const uint32_t size = SizeOfImage(base);
  auto* q = static_cast<const uint8_t*>(p);
  return q >= base && q + n <= base + size;
}

// The RTTI type name of a vtable (".?AVFoo@ns@@"), or nullptr. Same lookup as
// allocslab::RttiIs, bounds-checked against the image instead of SEH.
inline const char* RttiName(const uint8_t* base, void* const* vtbl) {
  if (!InImage(base, vtbl - 1, 8)) return nullptr;
  auto* col = static_cast<const Col*>(vtbl[-1]);
  if (!InImage(base, col, sizeof(Col)) || col->signature != 1) return nullptr;
  const uint8_t* name = base + col->typeDescriptor + 16;
  if (!InImage(base, name, 1)) return nullptr;
  return reinterpret_cast<const char*>(name);
}

// The vtable whose complete object locator names `rttiName` (exactly, or as
// a prefix when `prefix`) with COL offset `colOffset` (0 = the class's primary
// vtable; a secondary base's vtable has that base's offset). Returns it when
// there is exactly one, else nullptr; *count receives the number found.
// Pointer values in .rdata are compared with base + RVA and, for images that
// were mapped without relocation, with the header's ImageBase + RVA.
inline void** FindVtable(const uint8_t* base, const char* rttiName, uint32_t colOffset = 0, bool prefix = false,
                         int* count = nullptr) {
  if (count) *count = 0;
  Range rdata, data;
  if (!Section(base, ".rdata", rdata)) return nullptr;
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  const uint64_t bases[2] = {reinterpret_cast<uint64_t>(base), nt->OptionalHeader.ImageBase};
  const size_t nameLen = strlen(rttiName) + (prefix ? 0 : 1);  // with the terminator unless prefix
  void** found = nullptr;
  int n = 0;
  // Type descriptors live in .data: {pVFTable, spare, name[]}.
  auto scanTd = [&](Range r) {
    for (const uint8_t* p = r.begin; p + nameLen <= r.end; ++p) {
      p = static_cast<const uint8_t*>(memchr(p, rttiName[0], static_cast<size_t>(r.end - p)));
      if (!p || p + nameLen > r.end) break;
      if (memcmp(p, rttiName, nameLen) != 0 || p - 16 < base) continue;
      const uint32_t td = static_cast<uint32_t>(p - 16 - base);
      // Complete object locators in .rdata naming this descriptor.
      for (const uint8_t* c = rdata.begin; c + sizeof(Col) <= rdata.end; c += 4) {
        const Col* col = reinterpret_cast<const Col*>(c);
        if (col->typeDescriptor != td || col->signature != 1 || col->self != static_cast<uint32_t>(c - base) ||
            col->offset != colOffset)
          continue;
        // The vtable follows the pointer to its COL.
        for (uint64_t b : bases) {
          const uint64_t want = b + col->self;
          bool any = false;
          for (const uint8_t* q = rdata.begin; q + 16 <= rdata.end; q += 8) {
            uint64_t v;
            memcpy(&v, q, 8);
            if (v == want) {
              found = reinterpret_cast<void**>(const_cast<uint8_t*>(q + 8));
              ++n;
              any = true;
            }
          }
          if (any || bases[0] == bases[1]) break;
        }
      }
    }
  };
  if (Section(base, ".data", data)) scanTd(data);
  scanTd(rdata);  // some linkers merge .data-like RTTI into .rdata
  if (count) *count = n;
  return n == 1 ? found : nullptr;
}

inline void** FindVtable(HMODULE m, const char* rttiName, uint32_t colOffset = 0, bool prefix = false,
                         int* count = nullptr) {
  return FindVtable(ImageBase(m), rttiName, colOffset, prefix, count);
}

// ---------------------------------------------------------------------------
// Imports and exports by name (work on image-resource mappings too)
// ---------------------------------------------------------------------------

inline const char* CStrAt(const uint8_t* base, uint32_t rva) {
  const char* s = reinterpret_cast<const char*>(base + rva);
  return rva && InImage(base, s, 1) ? s : nullptr;
}

// RVA of the IAT slot importing `dll!name` (dll compared case-insensitively), or 0.
inline uint32_t ImportSlotRva(const uint8_t* base, const char* dll, const char* name) {
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  if (!nt) return 0;
  const IMAGE_DATA_DIRECTORY& dir = nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_IMPORT];
  if (!dir.VirtualAddress) return 0;
  for (auto* imp = reinterpret_cast<const IMAGE_IMPORT_DESCRIPTOR*>(base + dir.VirtualAddress);
       InImage(base, imp, sizeof(*imp)) && imp->Name; ++imp) {
    const char* d = CStrAt(base, imp->Name);
    if (!d || _stricmp(d, dll) != 0) continue;
    const uint32_t names = imp->OriginalFirstThunk ? imp->OriginalFirstThunk : imp->FirstThunk;
    for (uint32_t i = 0;; ++i) {
      auto* t = reinterpret_cast<const IMAGE_THUNK_DATA64*>(base + names + 8 * i);
      if (!InImage(base, t, 8) || !t->u1.AddressOfData) break;
      if (IMAGE_SNAP_BY_ORDINAL64(t->u1.Ordinal) || t->u1.AddressOfData >> 32) continue;
      const char* n = CStrAt(base, static_cast<uint32_t>(t->u1.AddressOfData) + 2);
      if (n && strcmp(n, name) == 0) return imp->FirstThunk + 8 * i;
    }
  }
  return 0;
}

// RVA of the export `name` (code or data), or 0 (also for forwarders).
inline uint32_t ExportRva(const uint8_t* base, const char* name) {
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  if (!nt) return 0;
  const IMAGE_DATA_DIRECTORY& dir = nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_EXPORT];
  auto* ed = reinterpret_cast<const IMAGE_EXPORT_DIRECTORY*>(base + dir.VirtualAddress);
  if (!dir.VirtualAddress || !InImage(base, ed, sizeof(*ed))) return 0;
  auto* names = reinterpret_cast<const uint32_t*>(base + ed->AddressOfNames);
  auto* ords = reinterpret_cast<const uint16_t*>(base + ed->AddressOfNameOrdinals);
  auto* funcs = reinterpret_cast<const uint32_t*>(base + ed->AddressOfFunctions);
  if (!InImage(base, names, 4 * ed->NumberOfNames) || !InImage(base, ords, 2 * ed->NumberOfNames) ||
      !InImage(base, funcs, 4 * ed->NumberOfFunctions))
    return 0;
  for (DWORD i = 0; i < ed->NumberOfNames; ++i) {
    const char* n = CStrAt(base, names[i]);
    if (!n || strcmp(n, name) != 0 || ords[i] >= ed->NumberOfFunctions) continue;
    const uint32_t rva = funcs[ords[i]];
    return rva >= dir.VirtualAddress && rva < dir.VirtualAddress + dir.Size ? 0 : rva;
  }
  return 0;
}

