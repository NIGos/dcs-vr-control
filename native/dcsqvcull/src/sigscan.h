// Strips the tag bits LoadLibraryEx sets on data/image-resource mappings.
inline const uint8_t* ImageBase(HMODULE m) {
  return reinterpret_cast<const uint8_t*>(reinterpret_cast<uintptr_t>(m) & ~static_cast<uintptr_t>(3));
}

inline const IMAGE_NT_HEADERS64* NtHeaders(const uint8_t* base) {
  if (!base) return nullptr;
  auto* dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
  if (dos->e_magic != IMAGE_DOS_SIGNATURE) return nullptr;
  auto* nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base + dos->e_lfanew);
  if (nt->Signature != IMAGE_NT_SIGNATURE || nt->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR64_MAGIC) return nullptr;
  return nt;
}

// Section by name (".text", ".rdata", ".data"). Returns false when absent.
inline bool Section(const uint8_t* base, const char* name, Range& out) {
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  if (!nt) return false;
  const IMAGE_SECTION_HEADER* s = IMAGE_FIRST_SECTION(nt);
  for (WORD i = 0; i < nt->FileHeader.NumberOfSections; ++i, ++s) {
    char n[9] = {};
    memcpy(n, s->Name, 8);
    if (strcmp(n, name) == 0) {
      out.begin = base + s->VirtualAddress;
      out.end = out.begin + (s->Misc.VirtualSize ? s->Misc.VirtualSize : s->SizeOfRawData);
      return true;
    }
  }
  return false;
}

inline uint32_t SizeOfImage(const uint8_t* base) {
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  return nt ? nt->OptionalHeader.SizeOfImage : 0;
}

// Calls f(Range) for every executable section.
template <typename F>
void ForEachCodeSection(const uint8_t* base, F&& f) {
  const IMAGE_NT_HEADERS64* nt = NtHeaders(base);
  if (!nt) return;
  const IMAGE_SECTION_HEADER* s = IMAGE_FIRST_SECTION(nt);
  for (WORD i = 0; i < nt->FileHeader.NumberOfSections; ++i, ++s)
    if (s->Characteristics & IMAGE_SCN_MEM_EXECUTE)
      f(Range{base + s->VirtualAddress, base + s->VirtualAddress + (s->Misc.VirtualSize ? s->Misc.VirtualSize : s->SizeOfRawData)});
}

// Number of matches of `pattern` in the module's code (counting stops at 2),
// and the match + offset when there is exactly one; nullptr otherwise
// (malformed pattern, no match, or ambiguous). `offset` is the manifest's
// signature offset: the location minus the pattern start.
inline uint8_t* FindUnique(const uint8_t* base, const char* pattern, ptrdiff_t offset = 0, int* count = nullptr) {
  Pattern pat;
  if (count) *count = 0;
  if (!Parse(pattern, pat)) return nullptr;
  const uint8_t* hit = nullptr;
  size_t n = 0;
  ForEachCodeSection(base, [&](Range r) {
    if (n >= 2) return;
    const uint8_t* h[2];
    const size_t k = FindAll(r, pat, h, 2, 2 - n);
    if (k && !n) hit = h[0];
    n += k;
  });
  if (count) *count = static_cast<int>(n);
  return n == 1 ? const_cast<uint8_t*>(hit) + offset : nullptr;
}

inline uint8_t* FindUnique(HMODULE m, const char* pattern, ptrdiff_t offset = 0, int* count = nullptr) {
  return FindUnique(ImageBase(m), pattern, offset, count);
}

