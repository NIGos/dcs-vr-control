// Runtime relocation of the production hooks' DCS locations.
//
// Every hook keeps its recorded RVA and its install-time checks (RTTI, slot
// targets, prologue bytes, FNV code hashes). It asks this resolver for the
// address instead of using the constant directly:
//   - on the DCS build the RVAs were derived from (module timestamp and size
//     equal to hook_sigs.h's kModules), or with [General] SigScan=0, every
//     call returns the recorded value and every check is today's exact check;
//   - on another build, each location of the module is looked up once, the
//     first time a hook asks for one: the recorded RVA if its signature still
//     matches there, else the unique match (RTTI type name + COL offset for
//     vtables, wildcard pattern for code, import/export name), else 0. A code
//     location is only accepted when its whole function hashes the same with
//     every displacement masked (masked FNV, hook_sigs.h), so code whose
//     logic changed resolves to 0 and its hook stays off. The hooks' own
//     checks then run against the resolved address; CodeIs, BytesAre and
//     SlotIs give the masked/relocated variants of those checks.
// Moves are logged ("reloc: <id> moved 0x.. -> 0x.."), with one summary
// line per module. Results are cached per id for the process.
//
// Signatures come from src/hook_sigs.h, generated by tools/gen_hook_sigs.py;
// docs/research/PATCH_PROCEDURE.md describes the workflow. Header-only,
// C++17; reads only inside the mapped image's sections.
